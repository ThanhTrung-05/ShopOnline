CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID     NUMBER(19)       NOT NULL,
    ORDER_NUMBER    VARCHAR2(50 CHAR) NOT NULL,
    OLD_STATUS      VARCHAR2(30 CHAR) NOT NULL,
    NEW_STATUS      VARCHAR2(30 CHAR) NOT NULL,
    MESSAGE         VARCHAR2(500 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP         DEFAULT SYSTIMESTAMP NOT NULL,
    READ_AT         TIMESTAMP,
    CONSTRAINT FK_NOTIFICATIONS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_NOTIFICATIONS_OLD_STATUS CHECK (OLD_STATUS IN (
        'PENDING','CONFIRMED','PAID','PAYMENT_FAILED',
        'SHIPPING','DELIVERED','CANCELLED','REFUNDED'
    )),
    CONSTRAINT CHK_NOTIFICATIONS_NEW_STATUS CHECK (NEW_STATUS IN (
        'PENDING','CONFIRMED','PAID','PAYMENT_FAILED',
        'SHIPPING','DELIVERED','CANCELLED','REFUNDED'
    )),
    CONSTRAINT CHK_NOTIFICATIONS_STATUS_CHANGE CHECK (OLD_STATUS <> NEW_STATUS)
);

CREATE INDEX IDX_NOTIFICATIONS_CUSTOMER_CREATED
    ON NOTIFICATIONS (CUSTOMER_ID, CREATED_AT DESC);

CREATE INDEX IDX_NOTIFICATIONS_CUSTOMER_UNREAD
    ON NOTIFICATIONS (CUSTOMER_ID, READ_AT);

COMMENT ON TABLE NOTIFICATIONS IS
    'Durable customer notifications created when an order status changes.';
COMMENT ON COLUMN NOTIFICATIONS.READ_AT IS
    'NULL while unread; timestamp records when the owning customer marked it read.';

COMMIT;
