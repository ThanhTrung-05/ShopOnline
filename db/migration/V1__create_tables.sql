-- ------------------------------------------------------------
-- TABLE: CUSTOMERS
-- Description: Stores all registered customer accounts
-- ------------------------------------------------------------
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID   NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL         VARCHAR2(200 CHAR) NOT NULL,
    FULL_NAME     VARCHAR2(200 CHAR) NOT NULL,
    PHONE         VARCHAR2(20 CHAR),
    PASSWORD_HASH VARCHAR2(60 CHAR)  NOT NULL,
    STATUS        VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY    VARCHAR2(100 CHAR),
    UPDATED_BY    VARCHAR2(100 CHAR),
    CONSTRAINT UK_CUSTOMERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_CUSTOMERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'BANNED'))
);

COMMENT ON TABLE  CUSTOMERS IS 'Registered customer accounts';
COMMENT ON COLUMN CUSTOMERS.EMAIL IS 'Unique email used as login identifier';
COMMENT ON COLUMN CUSTOMERS.PASSWORD_HASH IS 'BCrypt-12 hashed password (60 chars)';
COMMENT ON COLUMN CUSTOMERS.STATUS IS 'ACTIVE | INACTIVE | BANNED';

-- ------------------------------------------------------------
-- TABLE: REFRESH_TOKENS
-- Description: Stores hashed refresh tokens for JWT rotation
-- Single-use: token revoked after each use
-- ------------------------------------------------------------
CREATE TABLE REFRESH_TOKENS (
    TOKEN_ID    NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER(19)     NOT NULL,
    TOKEN_HASH  VARCHAR2(128 CHAR) NOT NULL,
    EXPIRES_AT  TIMESTAMP      NOT NULL,
    REVOKED     NUMBER(1)      DEFAULT 0 NOT NULL,
    REVOKED_AT  TIMESTAMP,
    CREATED_AT  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_REFRESH_TOKENS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_REFRESH_TOKENS_REVOKED CHECK (REVOKED IN (0, 1))
);

COMMENT ON TABLE  REFRESH_TOKENS IS 'JWT refresh tokens. Single-use with rotation.';
COMMENT ON COLUMN REFRESH_TOKENS.TOKEN_HASH IS 'SHA-256 hash of the actual refresh token UUID';
COMMENT ON COLUMN REFRESH_TOKENS.REVOKED IS '0=active, 1=revoked';

-- ------------------------------------------------------------
-- TABLE: CATEGORIES
-- Description: Product categories with self-referencing parent
-- ------------------------------------------------------------
CREATE TABLE CATEGORIES (
    CATEGORY_ID   NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_CODE VARCHAR2(50 CHAR) NOT NULL,
    CATEGORY_NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION   VARCHAR2(500 CHAR),
    PARENT_ID     NUMBER(19),
    SORT_ORDER    NUMBER(5)      DEFAULT 0 NOT NULL,
    STATUS        VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_CATEGORIES_CODE UNIQUE (CATEGORY_CODE),
    CONSTRAINT FK_CATEGORIES_PARENT FOREIGN KEY (PARENT_ID)
        REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CHK_CATEGORIES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

COMMENT ON TABLE  CATEGORIES IS 'Product category hierarchy';
COMMENT ON COLUMN CATEGORIES.PARENT_ID IS 'Self-referencing FK for subcategory hierarchy';

-- ------------------------------------------------------------
-- TABLE: PRODUCTS
-- Description: Product catalog
-- ------------------------------------------------------------
CREATE TABLE PRODUCTS (
    PRODUCT_ID   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_SLUG VARCHAR2(200 CHAR) NOT NULL,
    CATEGORY_ID  NUMBER(19)      NOT NULL,
    PRODUCT_NAME VARCHAR2(300 CHAR) NOT NULL,
    DESCRIPTION  CLOB,
    PRICE        NUMBER(19,2)    NOT NULL,
    IMAGE_URL    VARCHAR2(500 CHAR),
    STATUS       VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    VERSION      NUMBER(10)      DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(100 CHAR),
    UPDATED_BY   VARCHAR2(100 CHAR),
    CONSTRAINT UK_PRODUCTS_SLUG UNIQUE (PRODUCT_SLUG),
    CONSTRAINT FK_PRODUCTS_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CHK_PRODUCTS_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHK_PRODUCTS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

COMMENT ON TABLE  PRODUCTS IS 'Product catalog with pricing';
COMMENT ON COLUMN PRODUCTS.PRODUCT_SLUG IS 'URL-friendly unique identifier (e.g. nuoc-suoi-lavie-500ml)';
COMMENT ON COLUMN PRODUCTS.PRICE IS 'Unit price in VND. NUMBER(19,2) for precision.';
COMMENT ON COLUMN PRODUCTS.VERSION IS 'Optimistic locking version counter';

-- ------------------------------------------------------------
-- TABLE: INVENTORY
-- Description: Stock levels per product. 1:1 with PRODUCTS.
-- ------------------------------------------------------------
CREATE TABLE INVENTORY (
    INVENTORY_ID       NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID         NUMBER(19)  NOT NULL,
    QUANTITY           NUMBER(10)  DEFAULT 0 NOT NULL,
    RESERVED_QUANTITY  NUMBER(10)  DEFAULT 0 NOT NULL,
    VERSION            NUMBER(10)  DEFAULT 0 NOT NULL,
    UPDATED_AT         TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY         VARCHAR2(100 CHAR),
    CONSTRAINT UK_INVENTORY_PRODUCT UNIQUE (PRODUCT_ID),
    CONSTRAINT FK_INVENTORY_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_INVENTORY_QTY    CHECK (QUANTITY >= 0),
    CONSTRAINT CHK_INVENTORY_RSVD   CHECK (RESERVED_QUANTITY >= 0)
);

COMMENT ON TABLE  INVENTORY IS '1:1 with PRODUCTS. Pessimistic lock via SELECT FOR UPDATE.';
COMMENT ON COLUMN INVENTORY.QUANTITY IS 'Available quantity in warehouse';
COMMENT ON COLUMN INVENTORY.RESERVED_QUANTITY IS 'Reserved but not yet shipped';
COMMENT ON COLUMN INVENTORY.VERSION IS 'Optimistic lock version (backup to pessimistic)';

-- ------------------------------------------------------------
-- TABLE: CARTS
-- Description: Shopping cart per customer (one active at a time)
-- ------------------------------------------------------------
CREATE TABLE CARTS (
    CART_ID     NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER(19)  NOT NULL,
    STATUS      VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    VERSION     NUMBER(10)  DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CARTS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT CHK_CARTS_STATUS CHECK (STATUS IN ('ACTIVE', 'CHECKED_OUT', 'ABANDONED'))
);

COMMENT ON TABLE  CARTS IS 'Customer shopping cart. @Version for optimistic lock.';
COMMENT ON COLUMN CARTS.STATUS IS 'ACTIVE | CHECKED_OUT | ABANDONED';

-- ------------------------------------------------------------
-- TABLE: CART_ITEMS
-- Description: Items within a shopping cart
-- ------------------------------------------------------------
CREATE TABLE CART_ITEMS (
    CART_ITEM_ID NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CART_ID      NUMBER(19)  NOT NULL,
    PRODUCT_ID   NUMBER(19)  NOT NULL,
    QUANTITY     NUMBER(10)  NOT NULL,
    UNIT_PRICE   NUMBER(19,2) NOT NULL,
    ADDED_AT     TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CART_ITEMS_CART    FOREIGN KEY (CART_ID)    REFERENCES CARTS(CART_ID),
    CONSTRAINT FK_CART_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT UQ_CART_ITEMS_PRODUCT UNIQUE (CART_ID, PRODUCT_ID),
    CONSTRAINT CHK_CART_ITEMS_QTY CHECK (QUANTITY >= 1 AND QUANTITY <= 1000)
);

COMMENT ON TABLE  CART_ITEMS IS 'Items in a cart. UNIQUE(CART_ID, PRODUCT_ID) prevents duplicates.';

-- ------------------------------------------------------------
-- TABLE: ORDERS
-- Description: Customer orders. Partitioned by CREATED_AT.
-- ------------------------------------------------------------
CREATE TABLE ORDERS (
    ORDER_ID         NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID      NUMBER(19)     NOT NULL,
    ORDER_NUMBER     VARCHAR2(50 CHAR) NOT NULL,
    STATUS           VARCHAR2(30 CHAR) DEFAULT 'PENDING' NOT NULL,
    TOTAL_AMOUNT     NUMBER(19,2)   NOT NULL,
    SHIPPING_ADDRESS VARCHAR2(500 CHAR) NOT NULL,
    NOTE             VARCHAR2(1000 CHAR),
    CREATED_AT       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100 CHAR),
    UPDATED_BY       VARCHAR2(100 CHAR),
    CONSTRAINT UK_ORDERS_NUMBER UNIQUE (ORDER_NUMBER),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT CHK_ORDERS_STATUS CHECK (STATUS IN (
        'PENDING','CONFIRMED','PAID','PAYMENT_FAILED',
        'SHIPPING','DELIVERED','CANCELLED','REFUNDED'
    )),
    CONSTRAINT CHK_ORDERS_AMOUNT CHECK (TOTAL_AMOUNT >= 0)
)
PARTITION BY RANGE (CREATED_AT) (
    PARTITION ORDERS_2026_H1 VALUES LESS THAN (TIMESTAMP '2026-07-01 00:00:00'),
    PARTITION ORDERS_2026_H2 VALUES LESS THAN (TIMESTAMP '2027-01-01 00:00:00'),
    PARTITION ORDERS_2027_H1 VALUES LESS THAN (TIMESTAMP '2027-07-01 00:00:00'),
    PARTITION ORDERS_FUTURE   VALUES LESS THAN (MAXVALUE)
);

COMMENT ON TABLE  ORDERS IS 'Customer orders. Range-partitioned by CREATED_AT for performance.';
COMMENT ON COLUMN ORDERS.ORDER_NUMBER IS 'Business-facing order ID: ORD-YYYYMMDD-{UUID8}';

-- ------------------------------------------------------------
-- TABLE: ORDER_ITEMS
-- Description: Line items within an order (denormalized product name/price)
-- ------------------------------------------------------------
CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID      NUMBER(19)  NOT NULL,
    PRODUCT_ID    NUMBER(19)  NOT NULL,
    PRODUCT_NAME  VARCHAR2(300 CHAR) NOT NULL,
    QUANTITY      NUMBER(10)  NOT NULL,
    UNIT_PRICE    NUMBER(19,2) NOT NULL,
    SUBTOTAL      NUMBER(19,2) NOT NULL,
    CONSTRAINT FK_ORDER_ITEMS_ORDER   FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS(ORDER_ID),
    CONSTRAINT FK_ORDER_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_ORDER_ITEMS_QTY    CHECK (QUANTITY >= 1),
    CONSTRAINT CHK_ORDER_ITEMS_PRICE  CHECK (UNIT_PRICE >= 0),
    CONSTRAINT CHK_ORDER_ITEMS_SUB    CHECK (SUBTOTAL >= 0)
);

COMMENT ON TABLE  ORDER_ITEMS IS 'Denormalized order lines. PRODUCT_NAME captured at order time.';

-- ------------------------------------------------------------
-- TABLE: PAYMENTS
-- Description: Payment record per order. 1:1 with ORDERS.
-- Partitioned by CREATED_AT.
-- ------------------------------------------------------------
CREATE TABLE PAYMENTS (
    PAYMENT_ID      NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID        NUMBER(19)     NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
    TRANSACTION_REF VARCHAR2(100 CHAR),
    AMOUNT          NUMBER(19,2)   NOT NULL,
    STATUS          VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    QR_CODE         VARCHAR2(2000 CHAR),
    QR_EXPIRES_AT   TIMESTAMP,
    PAID_AT         TIMESTAMP,
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_PAYMENTS_ORDER        UNIQUE (ORDER_ID),
    CONSTRAINT UK_PAYMENTS_IDEMPOTENCY  UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT FK_PAYMENTS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    CONSTRAINT CHK_PAYMENTS_STATUS CHECK (STATUS IN (
        'PENDING','PROCESSING','SUCCESS','FAILED','EXPIRED','REFUNDED'
    )),
    CONSTRAINT CHK_PAYMENTS_AMOUNT CHECK (AMOUNT >= 0)
)
PARTITION BY RANGE (CREATED_AT) (
    PARTITION PAYMENTS_2026_H1 VALUES LESS THAN (TIMESTAMP '2026-07-01 00:00:00'),
    PARTITION PAYMENTS_2026_H2 VALUES LESS THAN (TIMESTAMP '2027-01-01 00:00:00'),
    PARTITION PAYMENTS_2027_H1 VALUES LESS THAN (TIMESTAMP '2027-07-01 00:00:00'),
    PARTITION PAYMENTS_FUTURE   VALUES LESS THAN (MAXVALUE)
);

COMMENT ON TABLE  PAYMENTS IS 'Payment records. IDEMPOTENCY_KEY prevents duplicate processing.';
COMMENT ON COLUMN PAYMENTS.IDEMPOTENCY_KEY IS 'Unique key per payment attempt: PAY-{orderId}-{uuid}';
COMMENT ON COLUMN PAYMENTS.QR_CODE IS 'Base64 QR image or VietQR string (max 15 min TTL)';

-- ------------------------------------------------------------
-- TABLE: OUTBOX_EVENTS
-- Description: Transactional outbox for Kafka publishing.
-- Written in same transaction as business data.
-- ------------------------------------------------------------
CREATE TABLE OUTBOX_EVENTS (
    EVENT_ID       NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGGREGATE_TYPE VARCHAR2(50 CHAR) NOT NULL,
    AGGREGATE_ID   VARCHAR2(50 CHAR) NOT NULL,
    EVENT_TYPE     VARCHAR2(100 CHAR) NOT NULL,
    PAYLOAD        CLOB           NOT NULL,
    STATUS         VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_AT   TIMESTAMP,
    ERROR_MESSAGE  VARCHAR2(2000 CHAR),
    RETRY_COUNT    NUMBER(5)      DEFAULT 0 NOT NULL,
    CONSTRAINT CHK_OUTBOX_STATUS CHECK (STATUS IN ('PENDING','PROCESSING','PROCESSED','FAILED'))
);

COMMENT ON TABLE  OUTBOX_EVENTS IS 'Transactional outbox. Relay polls and publishes to Kafka.';
COMMENT ON COLUMN OUTBOX_EVENTS.AGGREGATE_TYPE IS 'ORDER | PAYMENT | INVENTORY';
COMMENT ON COLUMN OUTBOX_EVENTS.EVENT_TYPE IS 'banhang.order.created | banhang.payment.success | etc.';
COMMENT ON COLUMN OUTBOX_EVENTS.PAYLOAD IS 'JSON event payload';

-- ------------------------------------------------------------
-- TABLE: PROCESSED_EVENTS
-- Description: Idempotency table for Kafka consumers.
-- Prevents duplicate event processing.
-- ------------------------------------------------------------
CREATE TABLE PROCESSED_EVENTS (
    ID             NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVENT_ID       VARCHAR2(100 CHAR) NOT NULL,
    CONSUMER_GROUP VARCHAR2(100 CHAR) NOT NULL,
    PROCESSED_AT   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_PROCESSED_EVENTS UNIQUE (EVENT_ID, CONSUMER_GROUP)
);

COMMENT ON TABLE  PROCESSED_EVENTS IS 'Kafka consumer idempotency. One row per event per consumer group.';
